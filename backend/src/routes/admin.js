const router = require('express').Router()
const { protect, requireAdmin } = require('../middleware/auth')
const uc = require('../controllers/userController')
const oc = require('../controllers/orderController')
const rc = require('../controllers/reviewController')
const cc = require('../controllers/couponController')
const bc = require('../controllers/brandController')
const catC = require('../controllers/categoryController')
const ac = require('../controllers/articleController')

router.use(protect, requireAdmin)
router.get('/users', uc.listUsers)
router.patch('/users/:id/status', uc.setUserStatus)
router.get('/orders', oc.listAdminOrders)
router.get('/orders/:id', oc.getMyOrder)
router.patch('/orders/:id/status', oc.updateOrderStatus)
router.get('/reviews', rc.listAdminReviews)
router.patch('/reviews/:id/status', rc.setReviewStatus)
router.delete('/reviews/:id', rc.deleteReview)
router.get('/coupons', cc.listCoupons)
router.post('/coupons', cc.createCoupon)
router.put('/coupons/:id', cc.updateCoupon)
router.delete('/coupons/:id', cc.deleteCoupon)
router.get('/brands', bc.listAdminBrands)
router.get('/categories', catC.listAdminCategories)
router.get('/articles', ac.getArticles)
router.post('/articles', ac.createArticle)
router.put('/articles/:id', ac.updateArticle)
router.delete('/articles/:id', ac.deleteArticle)

module.exports = router
